# Variables: espacio en memoria que se utiliza para almacenar cierto tipo de dato.

#Tipos de variables

# Guardamos texto dentro de una variable llamada nombre
nombre = "Ricardo"
print(nombre)
print(type(nombre))

name_1 = "Daniel"
edad = 25
ciudad = "México"

print(name_1)
print(edad)
print(ciudad)

print(type(name_1))
print(type(edad))
print(type(ciudad))

# Enteros (int)
num1 = 5
num2 = 10
print(num1)
print(num2)

# Operadores
print(num1 + num2) #Output: 15
print(num1 - num2) #Output: -5
print(num1 * num2) #Output: 50
print(num1 / num2) #Output: 0.5 División con decimal
print(num1 // num2) #Output: 0 División entera

# Flotantes (float)
